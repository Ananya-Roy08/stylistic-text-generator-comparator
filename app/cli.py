"""Command-line entry point: `python -m app.cli --help`."""
import argparse
import shutil
import textwrap


def _print_comparison(seed_prompt: str, outputs: dict[str, str]) -> None:
    column_width = max(18, (shutil.get_terminal_size((100, 24)).columns - 3) // 2)
    ngram_lines = textwrap.wrap(outputs["ngram"], width=column_width) or [""]
    lora_lines = textwrap.wrap(outputs["lora"], width=column_width) or [""]

    print(f"Seed prompt: {seed_prompt}\n")
    print(f"{'N-gram':<{column_width}} | LoRA-adapted LLM")
    print(f"{'-' * column_width}-+-{'-' * column_width}")
    for index in range(max(len(ngram_lines), len(lora_lines))):
        ngram_line = ngram_lines[index] if index < len(ngram_lines) else ""
        lora_line = lora_lines[index] if index < len(lora_lines) else ""
        print(f"{ngram_line:<{column_width}} | {lora_line}")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="stylistic-text-generator-comparator", description="Sports journalists use this to compare text generated by a LoRA-adapted LLM with an N-gram model, both fine-tuned on specific sports commentary styles.")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("hello", help="check that everything is wired up")
    compare = sub.add_parser("compare", help="compare N-gram and LoRA commentary")
    compare.add_argument("seed_prompt", help="shared seed prompt for both models")
    compare.add_argument("--max-new-tokens", type=int, default=40)
    compare.add_argument("--temperature", type=float, default=0.8)
    compare.add_argument("--top-p", type=float, default=0.9)
    args = parser.parse_args(argv)
    if args.command == "hello":
        print("Stylistic Text Generator Comparator is ready. Open README.md for your milestones.")
    elif args.command == "compare":
        from app.core import milestone_6

        outputs = milestone_6(
            args.seed_prompt,
            max_new_tokens=args.max_new_tokens,
            temperature=args.temperature,
            top_p=args.top_p,
        )
        _print_comparison(args.seed_prompt, outputs)


if __name__ == "__main__":
    main()
